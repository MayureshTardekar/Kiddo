  static List<QuizQuestion> questionsForLevel(GameLevel level) {
    final levelQuestions = quizQuestions
        .where((question) => level.questionIds.contains(question.id))
        .toList(growable: true);
    final extras =
        quizQuestions.where((question) => !levelQuestions.contains(question));
    levelQuestions.addAll(extras);
    return levelQuestions;
  }

  static List<LearningItem> matchItems() {
    return learningItems
        .where(
          (item) =>
              item.category == LearningCategory.colors ||
              item.category == LearningCategory.shapes ||
              item.category == LearningCategory.planets,
        )
        .toList(growable: false);
  }
